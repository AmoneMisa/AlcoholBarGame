import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {sharp,pixels,alphaBounds,trimSource,sourceRoot,outputRoot} from './painted-look-lib.mjs';
const faces=JSON.parse(await readFile(`${sourceRoot}/face-manifest.json`));
const outfits=JSON.parse(await readFile(`${sourceRoot}/outfit-manifest.json`));
const guides=JSON.parse(await readFile(`${sourceRoot}/guides/manifest.json`));
const trims=JSON.parse(await readFile(`${sourceRoot}/guides/trim-manifest.json`));
const result={};
for(const model of ['woman','man']){
 const dir=`${outputRoot}/${model}`;await mkdir(dir,{recursive:true});
 const assets={...faces[model].assets,...outfits[model]};
 const copy=async(name,file,bounds)=>assets[name]=await trimSource(file,`${dir}/${name}.png`,bounds);
 if(model==='woman')await copy('skin',`${sourceRoot}/sources/woman-skin-painterly-v2.png`,guides.woman.assets.skin.bounds);
 else{
  const src=`${sourceRoot}/sources/man-skin-painterly-v2.png`,meta=await sharp(src).metadata();
  for(const [name,rect,bounds] of [
   ['skin',[0,0,meta.width,Math.floor(meta.height*.38)],[238,81.75,124,177]],
   ['handLeft',[0,Math.floor(meta.height*.8),Math.floor(meta.width/2),meta.height-Math.floor(meta.height*.8)],[158.75,535.5,38.5,53.25]],
   ['handRight',[Math.floor(meta.width/2),Math.floor(meta.height*.8),meta.width-Math.floor(meta.width/2),meta.height-Math.floor(meta.height*.8)],[402.75,535.5,38.5,53.25]]
  ]){
   const bytes=await sharp(src).extract({left:rect[0],top:rect[1],width:rect[2],height:rect[3]}).png().toBuffer();
   const p=await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true}),b=alphaBounds(p.data,p.info);
   await sharp(bytes).extract(b).png().toFile(`${dir}/${name}.png`);assets[name]={file:`${name}.png`,bounds,native:[b.width,b.height],source:src};
  }
 }
 const oldGuides=JSON.parse(await readFile(`assets-src/character-studio/production/guides/${model}.json`));
 for(const side of ['Front','Back']){
  const style=model==='woman'?'cascade':'swept',version=model==='woman'&&side==='Front'?'v2':'v1';
  const guide=oldGuides.assets.find(a=>a.id===`Hair/${side}/${style}`);
  await copy(`hair${side}`,`${sourceRoot}/sources/${model}-hair-${side.toLowerCase()}-painterly-v2.png`,guide.logicalBounds);
 }
 for(const name of ['collar','belt','shoes']){
  const gp=await pixels(`${sourceRoot}/guides/${model}-${name}.png`),b=alphaBounds(gp.data,gp.info),base=trims[model][name];
  await copy(name,`${sourceRoot}/sources/${model}-${name}-v1.png`,[base[0]+b.left/4,base[1]+b.top/4,b.width/4,b.height/4]);
 }
 await copy('accessory',`${sourceRoot}/sources/${model}-accessory-v1.png`,guides[model].assets.accessory.bounds);
 await copy('iris',`${sourceRoot}/sources/iris-v1.png`,[-6.5,-6.5,13,13]);
 // The iris is deliberately compatible as an unpositioned texture, positioned by each rig.
 // A painted sclera texture fills the eye aperture behind the movable iris.
 const eye=`${sourceRoot}/sources/${model}-eye-v1.png`,em=await sharp(eye).metadata();
 const rect=model==='woman'?[.27,.39,.39,.28]:[.37,.43,.29,.18];
 const box={left:Math.round(em.width*rect[0]),top:Math.round(em.height*rect[1]),width:Math.round(em.width*rect[2]),height:Math.round(em.height*rect[3])};
 await sharp(eye).extract(box).png().toFile(`${dir}/sclera.png`);assets.sclera={file:'sclera.png',bounds:[250,139,100,26],native:[box.width,box.height],source:eye};
 // Mask only gold on the belt; gemstones and leather keep their own material color.
 const belt=await pixels(`${dir}/belt.png`);
 for(let y=0;y<belt.info.height;y++)for(let x=0;x<belt.info.width;x++){
  const i=(y*belt.info.width+x)*4,[r,g,b]=belt.data.subarray(i,i+3);
  const metal=model==='woman'?!(g>r*1.05&&g>b*1.1):x>belt.info.width*.41&&x<belt.info.width*.59;
  belt.data[i]=belt.data[i+1]=belt.data[i+2]=255;if(!metal)belt.data[i+3]=0;
 }
 await sharp(belt.data,{raw:belt.info}).png().toFile(`${dir}/belt-metal-mask.png`);assets.beltMask={file:'belt-metal-mask.png',bounds:assets.belt.bounds};
 result[model]={rig:faces[model].rig,assets};
}
await writeFile(`${outputRoot}/manifest.json`,JSON.stringify(result,null,2));
await writeFile('src/domain/characterStudio/paintedManifest.ts',`// Generated by scripts/pack-painted-look.mjs. Native PNG art; coordinates are logical rig units.\nexport default ${JSON.stringify(result)} as const;\n`);
console.log('Packed separate painted layers for both looks.');
