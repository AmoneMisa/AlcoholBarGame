#!/usr/bin/env node
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT=resolve('.');
const MOD=resolve(ROOT,'public/assets/bar/modular');
const MANIFESTS=resolve(ROOT,'scripts/modular-scenes');
const OUT=resolve(ROOT,'src/data/cosmetics/generatedModularScenes.ts');
const LOWER_POSITION=new Set(['speakeasy','jazz-cellar','art-deco','library','palace','tropical','desert','winter','beach','rooftop','cyberpunk','izakaya','marina','parisian','loft','riad']);

const clamp=(value,min=0,max=1)=>Math.max(min,Math.min(max,value));
const fraction=(value,size)=>{
  const number=Number(value);
  if(!Number.isFinite(number)) return undefined;
  return number>=-1&&number<=1 ? number : number/size;
};
const point=(value,author)=>{
  if(!value) return undefined;
  return {x:fraction(value.x,author.width),y:fraction(value.y,author.height)};
};
const rect=(value)=>value ? {
  x:Number(value.x),y:Number(value.y),width:Number(value.width),height:Number(value.height)
} : undefined;
const fmt=(value)=>Number(Number(value).toFixed(6));

function shelfGeometry(plan){
  const author=plan.authoringCanvas??plan.canvas;
  const shelfRect=rect(plan.slots?.shelves)??rect(plan.modules?.['shelf-reference']?.rect);
  const x0=clamp(shelfRect?.x??.2),x1=clamp((shelfRect?.x??.2)+(shelfRect?.width??.6));
  let planks=(plan.shelfRows??[]).map(value=>fraction(value,author.height)).filter(Number.isFinite).map(fmt);
  if(!planks.length){
    const top=shelfRect?.y??.15,height=shelfRect?.height??.4;
    planks=[top+height*.30,top+height*.58,top+height*.86].map(fmt);
  }
  return {x0:fmt(x0),x1:fmt(x1),planks};
}

function sceneDefinition(id,plan,manifest){
  const author=plan.authoringCanvas??plan.canvas;
  const required=plan.requiredRoles??['counter','shelf','seating'];
  const anchors=(plan.seatAnchors??[]).map(value=>point(value,author)).filter(Boolean);
  const seatCrop=manifest.manualSeatCutNormalized?.cropNormalized;
  const shelf=shelfGeometry(plan);
  const wall=rect(plan.slots?.wall);
  const counterSlot=rect(plan.slots?.counter);
  const seatingSlot=rect(plan.slots?.seating);
  const bartender=point(plan.bartenderAnchor,author);
  const back=fmt(clamp(wall?.height??counterSlot?.y??.6));
  const seat=required.includes('seating')
    ? fmt(clamp(anchors[0]?.y??((seatingSlot?.y??back+.1)+(seatingSlot?.height??.25)*.35)))
    : null;
  const layers=[
    {id:'architecture',role:'architecture',z:0,asset:`/assets/bar/modular/${id}/composite-ready/architecture.webp`}
  ];
  const shelfRect=rect(plan.modules?.['shelf-reference']?.rect)??rect(plan.slots?.shelves);
  if(required.includes('shelf')&&shelfRect) layers.push({
    id:'shelf',role:'shelves',z:10,asset:`/assets/bar/modular/${id}/composite-ready/shelf.webp`,selection:'shelf',rect:shelfRect
  });
  const counterRect=rect(plan.modules?.['counter-reference']?.rect)??counterSlot;
  if(required.includes('counter')&&counterRect) layers.push({
    id:'counter',role:'counter',z:20,asset:`/assets/bar/modular/${id}/composite-ready/counter.webp`,selection:'counter',rect:counterRect
  });
  if(required.includes('seating')&&seatCrop){
    for(const [index,anchor] of anchors.entries()){
      layers.push({
        id:`seat-${index+1}`,role:'seating',z:30,
        asset:`/assets/bar/modular/${id}/composite-ready/seat.webp`,selection:'seating',
        rect:{x:fmt(anchor.x-seatCrop.width/2),y:fmt(seatCrop.y),width:fmt(seatCrop.width),height:fmt(seatCrop.height)}
      });
    }
  }
  const bay=rect(plan.slots?.shelves)??shelfRect;
  const rowBaselines=bay ? shelf.planks.map(y=>fmt(clamp((y-bay.y)/bay.height,.05,.95))) : [];
  return {
    id,
    status:'authoring',
    canvas:plan.canvas,
    positionY:LOWER_POSITION.has(id)?.62:.5,
    geometry:{
      width:plan.canvas.width,height:plan.canvas.height,back,seat,
      stools:anchors.map(anchor=>fmt(anchor.x)),
      shelf,
      ...(bartender?.x!==undefined?{bartender:fmt(bartender.x)}:{})
    },
    layers,
    slots:plan.slots??{},
    ...((plan.windowCutouts??[]).length?{exterior:{enabled:true}}:{}),
    ...(bay?{shelfDecor:{
      z:15,bays:[{rect:bay,rowBaselines:rowBaselines.length?rowBaselines:[.3,.6,.9]}],
      panelTop:'#241914',panelBottom:'#100b09',rail:'#8b6438'
    }}:{}),
    lighting:{
      lightA:{x:.24,y:.10,radius:.58},
      lightB:{x:.79,y:.12,radius:.52},
      vignette:.12
    }
  };
}

const rows={};
for(const name of readdirSync(MOD).filter(name=>name!=='velvet').sort()){
  const planPath=resolve(MOD,name,'scene-plan.json');
  const manifestPath=resolve(MANIFESTS,`${name}.json`);
  let plan,manifest;
  try{
    plan=JSON.parse(readFileSync(planPath,'utf8'));
    manifest=JSON.parse(readFileSync(manifestPath,'utf8'));
  }catch{continue;}
  rows[name]=sceneDefinition(name,plan,manifest);
}

const body=`// Generated by scripts/build-generated-modular-scenes.mjs. Do not edit manually.
import type { ModularSceneDefinition } from './modularScenes';

export const GENERATED_MODULAR_SCENES = ${JSON.stringify(rows,null,2)} as const satisfies Readonly<Record<string,ModularSceneDefinition>>;
`;
writeFileSync(OUT,body);
console.log(`generated modular runtime scenes: ${Object.keys(rows).length}`);
