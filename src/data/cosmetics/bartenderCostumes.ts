export const REFERENCE_COSTUME_IDS = Object.values(BARTENDER_COSTUMES).flat().map(costume => costume.value);

export const bartenderCostumesFor = (character: string) =>
  BARTENDER_COSTUMES[character as keyof typeof BARTENDER_COSTUMES] ?? [];

export const bartenderCostumeFor = (character: string, outfit: string) => {
  const themed = themedCostumeFor(character, outfit);
  if (themed) return themed;
  const costumes = bartenderCostumesFor(character);
  const index = costumes.findIndex(costume => costume.value === outfit);
  if (index < 0) return undefined;
  return {
    ...costumes[index]!, index: index % 6, columns: 3, rows: 2, frameRatio: 316 / 552,
    sheet: `/assets/characters/bartender/${character}-costumes-atlas-v${Math.floor(index / 6) + 1}.webp`,
  };
};
